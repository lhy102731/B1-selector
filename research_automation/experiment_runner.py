class CodeChangeExecutor(abc.ABC):
    """Boundary to a code-change agent (e.g. Claude Code / GLM).

    apply() takes an optional ``experiment`` so executors that need the
    structured proposal (e.g. DeterministicBrickCodeExecutor reading
    scope['code_change']) can access it. Executors that don't need it ignore it.
    """

    @abc.abstractmethod
    def apply(self, task_path: Path, workspace: Path, experiment=None) -> CodeChangeResult:
        ...


class ClaudeCodeExecutor(CodeChangeExecutor):
    """Interface layer for `claude code <task>`.

    Intentionally NOT wired to a real process. It records the command that a real
    integration would run and refuses to execute, so nothing happens by accident.
    """

    def __init__(self, binary: str = "claude"):
        self.binary = binary
        self.last_command: list[str] | None = None

    def build_command(self, task_path: Path) -> list[str]:
        return [self.binary, "code", str(task_path)]

    def apply(self, task_path: Path, workspace: Path, experiment=None) -> CodeChangeResult:
        self.last_command = self.build_command(task_path)
        return CodeChangeResult(
            ok=False,
            error="ClaudeCodeExecutor is an interface stub; wire a real runner to execute "
                  + " ".join(self.last_command),
            logs=[f"planned: {' '.join(self.last_command)}"],
        )


