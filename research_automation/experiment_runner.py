class BacktestResultAdapter:
    """Maps existing project outputs (backtest_equity*.csv / backtest_trades*.csv /
    metrics.json / report.md / captured stdout) into a normalized metrics.json that
    the existing BacktestResultParser can read, and returns StandardMetrics.

    Strategy-code untouched: this only reads outputs and stdout.
    """

    # stdout patterns from run_b1_v3.py and backtest_optimized.py print_summary
    _PATTERNS = {
        "total_return": [r"Return:\s*(-?\d+(?:\.\d+)?)\s*%", r"总收益率[:：]\s*(-?\d+(?:\.\d+)?)\s*%"],
        "win_rate": [r"WR:\s*(-?\d+(?:\.\d+)?)\s*%", r"胜率[:：]\s*(-?\d+(?:\.\d+)?)\s*%"],
        "max_drawdown": [r"DD:\s*(-?\d+(?:\.\d+)?)\s*%", r"最大回撤[:：]\s*(-?\d+(?:\.\d+)?)\s*%"],
        "sharpe": [r"Sharpe:\s*(-?\d+(?:\.\d+)?)"],
        "profit_factor": [r"PF:\s*(-?\d+(?:\.\d+)?)"],
        "trades": [r"\bT:\s*(\d+)", r"交易数[:：]\s*(\d+)"],
    }

    def parse_stdout(self, stdout: str) -> dict:
        found: dict = {}
        for key, pats in self._PATTERNS.items():
            for p in pats:
                m = re.search(p, stdout or "")
                if m:
                    found[key] = float(m.group(1)) if key != "trades" else int(m.group(1))
                    break
        return found

    def write_metrics_json(self, result_dir: Path, stdout: str, mode: str = "b1_stdout") -> Path:
        """Build a parser-friendly metrics.json from stdout, per strategy metric_mode."""
        if mode == "brick_v2_stdout":
            metrics_json = self._parse_brick_v2(stdout)
        else:
            raw = self.parse_stdout(stdout)
            metrics_json = {
                "sharpe": raw.get("sharpe"),
                "win_rate": raw.get("win_rate"),       # percent, parser normalizes to fraction
                "max_drawdown": raw.get("max_drawdown"),
                "trades": raw.get("trades"),
                "total_return": raw.get("total_return"),
                "profit_factor": raw.get("profit_factor"),
            }
        result_dir.mkdir(parents=True, exist_ok=True)
        path = result_dir / "metrics.json"
        path.write_text(json.dumps(metrics_json, ensure_ascii=False, indent=2), encoding="utf-8")
        return path

    @staticmethod
    def _parse_brick_v2(stdout: str) -> dict:
        """Brick V2 stdout: 'Total: N', 'Win rate: X%', 'Avg return: +Y%'.
        Objective = avg per-trade return (no sharpe in V2 stdout)."""
        out = {"sharpe": None, "win_rate": None, "total_return": None, "trades": None,
               "max_drawdown": None}
        m = re.search(r"Total:\s*(\d+)", stdout or "")
        if m:
            out["trades"] = int(m.group(1))
        m = re.search(r"Win rate:\s*([\d.]+)\s*%", stdout or "")
        if m:
            out["win_rate"] = float(m.group(1))
        m = re.search(r"Avg return:\s*([+-]?[\d.]+)\s*%", stdout or "")
        if m:
            out["total_return"] = float(m.group(1))   # avg per-trade return as the scalar objective
        return out

    def to_standard_metrics(self, result_dir: Path) -> StandardMetrics:
        return BacktestResultParser().parse(result_dir)


class RealBacktestExecutor(BacktestExecutor):
    """Real executor: runs an existing backtest entrypoint via subprocess.

    - discovers entrypoints under the project root
    - maps experiment.scope params to that entrypoint's CLI flags
    - if a requested param cannot be passed via CLI -> returns a patch_plan and
      requires_manual_integration=true WITHOUT running or modifying any code
    - captures stdout/stderr, copies output csvs into result_dir, and uses
      BacktestResultAdapter to emit a normalized metrics.json
    """

    def __init__(self, project_root: str | Path | None = None, output_root: str | Path = "research_automation/_output",
                 timeout: int = 3600, python_exe: str | None = None, keep_scratch: bool = False,
                 workspace_mode: bool = False, workspace_manager=None,
                 subprocess_sink=None):
        self.root = Path(project_root) if project_root else _PROJECT_ROOT
        self.output_root = Path(output_root)
        self.timeout = timeout
        self.python_exe = python_exe or sys.executable
        self.keep_scratch = keep_scratch
        self.adapter = BacktestResultAdapter()
        # Sandbox: when True, the entrypoint script is copied into a per-experiment
        # workspace and launched from there, so ``from strategy.*`` resolves to the
        # workspace copy (the script's sys.path.insert(0, __file__.parent) points at
        # the workspace). cwd stays self.root so Path('data') + from utils.* still
        # hit production. Production strategy/ + script are never written.
        self.workspace_mode = workspace_mode
        self.workspace_manager = workspace_manager
        self.subprocess_sink = subprocess_sink

    # ---- discovery (for audit / selection) --------------------------------
    def discover_entrypoints(self) -> dict:
        found = {}
        for name in ("run_b1_v3.py", "backtest_optimized.py", "run_b3.py"):
            p = self.root / name
            if p.exists():
                found[name] = str(p)
        for p in sorted(self.root.glob("backtest*.py")):
            found.setdefault(p.name, str(p))
        return found

    def _select_spec(self, strategy: str) -> EntrypointSpec:
        return _STRATEGY_SPECS.get((strategy or "").upper(), _OPT_SPEC)

    @staticmethod
    def _extract_scope(experiment) -> dict:
        if isinstance(experiment, dict):
            return experiment
        sc = getattr(experiment, "scope", None)
        if isinstance(sc, dict):
            return sc
        strat = getattr(experiment, "strategy", None)
        prop = getattr(experiment, "proposal", None)
        pscope = getattr(prop, "scope", None)
        if isinstance(pscope, dict):
            # Full scope dict (carries params + start/end/max_stocks) -> pass through
            # so global flags actually reach the entrypoint (avoids whole-universe default).
            # Strip code_change -- it's for the code executor, not a backtest CLI flag.
            # global_flags keys (start/end/max_stocks) must stay at scope top-level,
            # not be nested inside params. Everything else goes into params.
            _GLOBAL_KEYS = {"start", "end", "max_stocks", "sample", "workers"}
            clean = {k: v for k, v in pscope.items() if k != "code_change"}
            if "params" in clean:
                return {"strategy": strat or pscope.get("strategy", "B1"), **clean}
            top = {k: v for k, v in clean.items() if k in _GLOBAL_KEYS}
            rest = {k: v for k, v in clean.items() if k not in _GLOBAL_KEYS}
            return {"strategy": strat or "B1", "params": rest, **top}
        return {"strategy": strat or "B1", "params": {}}

    @staticmethod
    def _fmt(value, is_bool: bool) -> str:
        if is_bool:
            return "true" if value in (True, "true", "True", 1) else "false"
        return str(value)

    # ---- main API ---------------------------------------------------------
    def execute(
        self,
        experiment,
        result_dir: str | Path | None = None,
        dry_run: bool = False,
        workspace_path: str | Path | None = None,
        *,
        lease=None,
        invocation=None,
        execution_lease=None,
        execution_invocation=None,
        authority_reader=None,
        repository_root: str | Path | None = None,
    ) -> dict:
        lease = lease if lease is not None else execution_lease
        invocation = invocation if invocation is not None else execution_invocation
        if not isinstance(lease, TaskExecutionLease) or not isinstance(
            invocation, ExecutionInvocation
        ):
            return {
                "success": False,
                "error": "execution lease and invocation are required before backtest execution",
                "requires_manual_integration": False,
                "command": None,
            }
        try:
            reader = authority_reader if isinstance(authority_reader, AuthorityReader) else AuthorityReader()
            guard = ExecutionSinkGuard(
                authority_reader=reader,
                repository_root=repository_root or self.root,
            )
            permit = guard.authorize(lease, invocation)
            if (
                permit.operation != "SUBPROCESS"
                or permit.effect is not SideEffect.START_SUBPROCESS
            ):
                raise ExecutionAuthorizationError(
                    "backtest execution requires a START_SUBPROCESS intent"
                )
        except (ExecutionAuthorizationError, OSError, ValueError) as error:
            return {
                "success": False,
                "error": f"execution authorization rejected: {error}",
                "requires_manual_integration": False,
                "command": None,
            }
        scope = self._extract_scope(experiment)
        strategy = (scope.get("strategy") or "B1").upper()
        params = scope.get("params") or {}
        spec = self._select_spec(strategy)

        # Sandbox: copy strategy/ + config/ + entrypoint script into a workspace and
        # launch the workspace copy. ``from strategy.*`` then resolves to the workspace
        # copy (script's sys.path.insert(0, __file__.parent) -> workspace); cwd stays
        # self.root so Path('data') + from utils.* still hit production.
        # If the caller (AutomationController) already created the workspace and
        # staged code edits in it, reuse that path -- never re-create, or the edits
        # would be overwritten by a fresh copy from production.
        ws_path = None
        if workspace_path is not None:
            ws_path = Path(workspace_path)
            if not ws_path.exists():
                return {"success": False, "error": f"workspace not found: {ws_path}",
                        "requires_manual_integration": False}
        elif self.workspace_mode and self.workspace_manager is not None:
            return {
                "success": False,
                "error": "a pre-created, intent-bound workspace_path is required",
                "requires_manual_integration": False,
                "command": None,
            }
        if ws_path is not None:
            script_path = ws_path / spec.script
            if not script_path.exists():
                return {"success": False, "error": f"workspace entrypoint not found: {spec.script}",
                        "requires_manual_integration": False}
        else:
            script_path = self.root / spec.script
            if not script_path.exists():
                return {"success": False, "error": f"entrypoint not found: {spec.script}",
                        "requires_manual_integration": False}

        # detect params that cannot be passed via CLI
        unmapped = {k: v for k, v in params.items()
                    if k not in spec.param_flags and not k.startswith("q_")}
        if unmapped:
            return {
                "success": False,
                "requires_manual_integration": True,
                "patch_plan": {
                    "reason": "scope params have no CLI flag on the selected entrypoint",
                    "entrypoint": spec.script,
                    "unmapped_params": unmapped,
                    "suggested_manual_steps": [
                        f"Expose these params as CLI flags in {spec.script}, OR",
                        "set them in config/strategy_params.yaml and re-scope the experiment.",
                    ],
                    "do_not_auto_apply": True,
                },
                "command": None,
            }

        # build argv (subprocess only; no shell, no eval/exec)
        eid = getattr(experiment, "experiment_id", None) or scope.get("experiment_id") or f"adhoc-{int(time.time())}"
        if ws_path is not None:
            # workspace mode: results land in <exp_id>/outputs next to the workspace
            rdir = Path(result_dir) if result_dir else (ws_path.parent / "outputs")
            script_arg = str(script_path)
        else:
            rdir = Path(result_dir) if result_dir else (self.output_root / eid / "result")
            script_arg = spec.script
        argv = [self.python_exe, script_arg]
        if spec.subcommand:
            argv.append(spec.subcommand)
        for k, flag in spec.global_flags.items():
            if scope.get(k) is not None:
                argv += [flag, str(scope[k])]
        for k, v in params.items():
            if k in spec.param_flags:
                argv += [spec.param_flags[k], self._fmt(v, k in spec.bool_params)]
            elif k.startswith("q_"):
                argv += ["--" + k.replace("_", "-"), self._fmt(v, False)]

        if tuple(argv) != permit.argv:
            return {
                "success": False,
                "error": "backtest command differs from immutable execution intent",
                "requires_manual_integration": False,
                "command": None,
            }
        if invocation.cwd is None or Path(invocation.cwd).resolve() != self.root.resolve():
            return {
                "success": False,
                "error": "backtest working directory differs from immutable execution intent",
                "requires_manual_integration": False,
                "command": None,
            }
        required_resources = {
            script_path.resolve(),
            rdir.resolve(),
        }
        if ws_path is not None:
            required_resources.add(ws_path.resolve())
        if not required_resources.issubset(set(permit.resource_paths)):
            return {
                "success": False,
                "error": "backtest resources differ from immutable execution intent",
                "requires_manual_integration": False,
                "command": None,
            }

        if dry_run:
            return {"success": True, "dry_run": True, "command": argv,
                    "entrypoint": spec.script, "requires_manual_integration": False,
                    "workspace_path": str(ws_path) if ws_path else None}

        # run -- cwd stays project root (read production data/utils); in workspace
        # mode, PYTHONPATH points at the workspace as a belt-and-suspenders so the
        # workspace strategy/ is preferred even before the script's own sys.path hack.
        run_env = None
        if ws_path is not None:
            run_env = dict(os.environ)
            run_env["PYTHONPATH"] = str(ws_path) + (os.pathsep + run_env["PYTHONPATH"]
                                                     if run_env.get("PYTHONPATH") else "")
        # Shared entrypoints write fixed names in the repository root. Preserve
        # every pre-run file transactionally: the child may overwrite it before
        # we get a chance to inspect ownership.
        output_candidates = {self.root / spec.equity_output, self.root / spec.trades_output}
        for pattern in spec.output_globs:
            output_candidates.update(self.root.glob(pattern))
        preexisting_outputs = {p.resolve() for p in output_candidates if p.exists()}
        backup_dir = Path(tempfile.mkdtemp(prefix="ag2-backtest-output-"))
        backups = {}
        for i, original in enumerate(sorted(preexisting_outputs, key=str)):
            backup = backup_dir / f"{i:04d}-{original.name}"
            shutil.copy2(original, backup)
            backups[original] = backup

        def restore_preexisting() -> None:
            for original, backup in backups.items():
                original.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(backup, original)
            shutil.rmtree(backup_dir, ignore_errors=True)

        def _authorized_runner(command, **kwargs):
            kwargs.setdefault("capture_output", True)
            kwargs.setdefault("text", True)
            kwargs.setdefault("encoding", "utf-8")
            kwargs.setdefault("errors", "replace")
            return subprocess.run(
                command,
                timeout=self.timeout,
                env=run_env,
                **kwargs,
            )

        sink = self.subprocess_sink or AuthorizedSubprocess(
            authority_reader=reader,
            repository_root=repository_root or self.root,
            runner=_authorized_runner,
        )
        try:
            proc = sink.run(lease, invocation)
        except subprocess.TimeoutExpired as e:
            restore_preexisting()
            return {"success": False, "error": f"timeout after {self.timeout}s",
                    "command": argv, "stdout": e.stdout or "", "stderr": e.stderr or ""}
        except ExecutionAuthorizationError as e:
            restore_preexisting()
            return {"success": False, "error": f"execution authorization rejected: {e}",
                    "command": argv}
        except Exception as e:
            restore_preexisting()
            return {"success": False, "error": f"subprocess error: {e}", "command": argv}

        rdir.mkdir(parents=True, exist_ok=True)
        # copy outputs from project root into the result dir (archival), then
        # delete the root scratch CSVs so the repo root stays clean (keep_scratch opt-out).
        equity_path = trades_path = None
        src_eq = self.root / spec.equity_output
        src_tr = self.root / spec.trades_output
        scratch_cleaned = []
        run_succeeded = proc.returncode == 0
        if run_succeeded and src_eq.exists():
            equity_path = rdir / "equity.csv"
            shutil.copyfile(src_eq, equity_path)
            if not self.keep_scratch and src_eq.resolve() not in preexisting_outputs:
                try:
                    src_eq.unlink(); scratch_cleaned.append(spec.equity_output)
                except OSError:
                    pass
        if run_succeeded and src_tr.exists():
            trades_path = rdir / "trades.csv"
            shutil.copyfile(src_tr, trades_path)
            if not self.keep_scratch and src_tr.resolve() not in preexisting_outputs:
                try:
                    src_tr.unlink(); scratch_cleaned.append(spec.trades_output)
                except OSError:
                    pass
        # Dynamic-named outputs (for example Brick artifacts): archive + clean.
        for pattern in spec.output_globs if run_succeeded else ():
            for f in self.root.glob(pattern):
                try:
                    shutil.copyfile(f, rdir / f.name)
                    if not self.keep_scratch and f.resolve() not in preexisting_outputs:
                        f.unlink(); scratch_cleaned.append(f.name)
                except OSError:
                    pass
        # Restore old shared files after archiving this run's successful output.
        # On failure, no output is archived/deleted, but old files are still restored.
        restore_preexisting()
        # normalize metrics from stdout into result_dir/metrics.json (strategy-aware)
        metrics_path = self.adapter.write_metrics_json(rdir, proc.stdout or "", mode=spec.metric_mode)

        return {
            "success": proc.returncode == 0,
            "returncode": proc.returncode,
            "requires_manual_integration": False,
            "command": argv,
            "metrics_path": str(metrics_path),
            "equity_path": str(equity_path) if equity_path else None,
            "trades_path": str(trades_path) if trades_path else None,
            "scratch_cleaned": scratch_cleaned,
            "stdout": proc.stdout or "",
            "stderr": proc.stderr or "",
            "workspace_path": str(ws_path) if ws_path else None,
            "metadata_path": str(ws_path / "metadata.json") if ws_path else None,
        }

    # ---- BacktestExecutor ABC adapter (drop-in for AutomationController) ---
    def run(self, experiment: Experiment, workspace: Path, result_dir: Path) -> BacktestResult:
        # If the controller handed us a real workspace dir (created in IMPLEMENTING),
        # pass it through so execute() reuses it instead of re-creating (which would
        # overwrite staged code edits). Otherwise workspace_path stays None.
        ws_arg = None
        if workspace is not None:
            wp = Path(workspace)
            if wp.is_dir() and (wp / "metadata.json").exists():
                ws_arg = wp
        res = self.execute(experiment, result_dir=result_dir, workspace_path=ws_arg)
        if res.get("requires_manual_integration"):
            return BacktestResult(result_dir=str(result_dir), ok=False,
                                  error="requires_manual_integration",
                                  logs=[json.dumps(res.get("patch_plan", {}), ensure_ascii=False)])
        return BacktestResult(
            result_dir=str(result_dir),
            ok=bool(res.get("success")),
            anomaly=False,
            error=res.get("error"),
            logs=[" ".join(res.get("command") or [])]
                 + ([res.get("stderr", "")[:2000]] if not res.get("success") and res.get("stderr") else []),
        )
