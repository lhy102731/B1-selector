# Deterministic code-change executor (NO LLM) -- code-experiment loop
# ============================================================
# Files this executor is allowed to modify. Anything outside is rejected.
ALLOWED_CODE_CHANGE_FILES = {"strategy/brick_chart_strategy.py"}


def _ast_replace_constant(source: str, symbol: str, new_value) -> tuple[str, str]:
    """Locate a named constant via AST and replace ONLY its value text.

    Robust to formatting (handles ``'symbol': 2.0 / 3.0`` inside a dict literal,
    module/class-level ``symbol = 2/3`` and ``SYMBOL = 2/3``). Uses the value
    node's precise (lineno, col_offset, end_lineno, end_col_offset) span to splice
    the new value into the original text -- comments and all other formatting are
    preserved (unlike ast.unparse which rewrites the whole file).

    Returns (new_source, old_value_expr). Raises ValueError if symbol not found.
    """
    tree = ast.parse(source)
    value_node = None

    for node in ast.walk(tree):
        if value_node is not None:
            break
        # dict literal: {'symbol': <value>, ...}
        if isinstance(node, ast.Dict):
            for k, v in zip(node.keys, node.values):
                if isinstance(k, ast.Constant) and k.value == symbol:
                    value_node = v
                    break
        # assignment: symbol = <value>  /  SYMBOL = <value>
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id == symbol:
                    value_node = node.value
                    break
        # annotated assignment: symbol: T = <value>
        elif isinstance(node, ast.AnnAssign):
            if isinstance(node.target, ast.Name) and node.target.id == symbol and node.value is not None:
                value_node = node.value

    if value_node is None:
        raise ValueError(f"symbol '{symbol}' not found as a dict key or assignment target")

    old_expr = ast.unparse(value_node)

    lines = source.splitlines(keepends=True)
    # offsets are 1-based line, 0-based col
    sl, sc = value_node.lineno - 1, value_node.col_offset
    el, ec = value_node.end_lineno - 1, value_node.end_col_offset

    # compute absolute char positions of the value span
    def _abs(line_idx: int, col: int) -> int:
        return sum(len(lines[i]) for i in range(line_idx)) + col

    start = _abs(sl, sc)
    end = _abs(el, ec)
    new_source = source[:start] + repr(new_value) + source[end:]

    # sanity: result must still parse (guards against a broken splice)
    ast.parse(new_source)
    return new_source, old_expr


class DeterministicBrickCodeExecutor(CodeChangeExecutor):
    """Deterministic (NO LLM) code-change executor for the code-experiment loop.

    Reads a structured code_change from experiment.proposal.scope['code_change']:
        {change_type: 'modify_constant', file, symbol, value}
    Applies it to the WORKSPACE copy ONLY (never production), records a diff in
    workspace/code_change.json, and returns the changed file list. Used to prove
    the change-code -> backtest -> evaluate loop before any LLM is wired in.
    """

    @staticmethod
    def _extract_code_change(experiment) -> dict | None:
        if experiment is None:
            return None
        if isinstance(experiment, dict):
            scope = experiment.get("scope") or {}
            if isinstance(scope, dict) and "code_change" in scope:
                return scope["code_change"]
            return experiment.get("code_change")
        prop = getattr(experiment, "proposal", None)
        scope = getattr(prop, "scope", None)
        if isinstance(scope, dict):
            return scope.get("code_change")
        return None

    def apply(self, task_path: Path, workspace: Path, experiment=None) -> CodeChangeResult:
        cc = self._extract_code_change(experiment)
        if not cc:
            return CodeChangeResult(ok=False, error="no code_change in experiment.scope",
                                    logs=["deterministic executor: nothing to apply"])

        change_type = cc.get("change_type")
        rel_file = cc.get("file")
        symbol = cc.get("symbol")
        value = cc.get("value")

        if change_type != "modify_constant":
            return CodeChangeResult(ok=False, error=f"unsupported change_type: {change_type}")
        if rel_file not in ALLOWED_CODE_CHANGE_FILES:
            return CodeChangeResult(
                ok=False,
                error=f"file not in ALLOWED_CODE_CHANGE_FILES: {rel_file}",
                logs=[f"allowed: {sorted(ALLOWED_CODE_CHANGE_FILES)}"],
            )

        target = Path(workspace) / rel_file
        # guard: only ever write inside the safe output roots (the workspace copy)
        assert_safe_path(target)
        if not target.exists():
            return CodeChangeResult(ok=False, error=f"workspace target not found: {target}")

        before = target.read_text(encoding="utf-8")
        before_hash = hashlib.sha256(before.encode("utf-8")).hexdigest()
        try:
            new_src, old_expr = _ast_replace_constant(before, symbol, value)
        except (ValueError, SyntaxError) as e:
            return CodeChangeResult(ok=False, error=f"ast replace failed: {e}")

        target.write_text(new_src, encoding="utf-8")
        after_hash = hashlib.sha256(new_src.encode("utf-8")).hexdigest()

        # diff record for future AG2 traceability (constraint 2)
        diff = {
            "file": rel_file,
            "change_type": change_type,
            "symbol": symbol,
            "old_value": old_expr,
            "new_value": value,
            "before_hash": before_hash,
            "after_hash": after_hash,
        }
        diff_path = Path(workspace) / "code_change.json"
        assert_safe_path(diff_path)
        diff_path.write_text(json.dumps(diff, ensure_ascii=False, indent=2), encoding="utf-8")

        return CodeChangeResult(
            changed_files=[rel_file],
            deleted_files=[],
            schema_changes=False,
            git_commit=None,
            logs=[f"modify_constant {symbol}: {old_expr} -> {value!r} in workspace copy "
                  f"({before_hash[:12]} -> {after_hash[:12]})"],
        )


